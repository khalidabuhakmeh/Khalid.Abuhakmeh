// Converts assets/avatar-neutral.png into src/Khalid.Abuhakmeh/Avatar.g.cs.
// Usage: dotnet run --project tools/AvatarGen -- [input.png] [output.cs] [cols] [cropLeft cropTop cropSize]
using System.Text;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;
using SixLabors.ImageSharp.Processing;

var input = args.Length > 0 ? args[0] : "assets/avatar-neutral.png";
var output = args.Length > 1 ? args[1] : "src/Khalid.Abuhakmeh/Avatar.g.cs";
var cols = args.Length > 2 ? int.Parse(args[2]) : 36;
var rows = cols / 2;

// Crop to halo + shoulders (source is 400x400).
var crop = args.Length > 5
    ? new Rectangle(int.Parse(args[3]), int.Parse(args[4]), int.Parse(args[5]), int.Parse(args[5]))
    : new Rectangle(52, 52, 296, 296);

// Palette sampled from the avatar.
var palette = new (string Hex, Rgb24 Rgb)[]
{
    ("#0A0A0A", new Rgb24(0x0A, 0x0A, 0x0A)), // black (background, outlines, beard)
    ("#8B0000", new Rgb24(0x8B, 0x00, 0x00)), // crimson halo / shirt
    ("#FBEAEA", new Rgb24(0xFB, 0xEA, 0xEA)), // white / skin
    ("#E8A0A0", new Rgb24(0xE8, 0xA0, 0xA0)), // shadow pink
};

int Nearest(Rgb24 p)
{
    var best = 0; var bestD = int.MaxValue;
    for (var i = 0; i < palette.Length; i++)
    {
        var q = palette[i].Rgb;
        int dr = p.R - q.R, dg = p.G - q.G, db = p.B - q.B;
        var d = dr * dr + dg * dg + db * db;
        if (d < bestD) { bestD = d; best = i; }
    }
    return best;
}

using var src = Image.Load<Rgb24>(input);
src.Mutate(c => c.Crop(crop));

// --- Mono: cols x rows, luminance ramp -------------------------------------
const string ramp = " .:-=+*#%@";
using var small = src.Clone(c => c.Resize(cols, rows, KnownResamplers.Box));
var lums = new double[cols, rows];
double min = 1, max = 0;
for (var y = 0; y < rows; y++)
    for (var x = 0; x < cols; x++)
    {
        var p = small[x, y];
        var l = (0.2126 * p.R + 0.7152 * p.G + 0.0722 * p.B) / 255.0;
        lums[x, y] = l; min = Math.Min(min, l); max = Math.Max(max, l);
    }
var mono = new StringBuilder();
for (var y = 0; y < rows; y++)
{
    var line = new StringBuilder();
    for (var x = 0; x < cols; x++)
    {
        var l = (lums[x, y] - min) / (max - min);
        l = Math.Pow(l, 0.8);
        line.Append(ramp[Math.Clamp((int)(l * ramp.Length), 0, ramp.Length - 1)]);
    }
    mono.AppendLine(line.ToString().TrimEnd());
}

// --- Color: half blocks (cols x rows*2 pixels), runs grouped by palette ----
using var px = src.Clone(c => c.Resize(cols, rows * 2, KnownResamplers.Box));
var idx = new int[cols, rows * 2];
for (var y = 0; y < rows * 2; y++)
    for (var x = 0; x < cols; x++) idx[x, y] = Nearest(px[x, y]);

var color = new StringBuilder();
for (var r = 0; r < rows; r++)
{
    var runFg = -1; var runBg = -1; var open = false;
    for (var x = 0; x < cols; x++)
    {
        int top = idx[x, r * 2], bot = idx[x, r * 2 + 1];
        char ch; int fg, bg;
        if (top == bot) { ch = ' '; fg = top; bg = top; }
        else { ch = '\u2580'; fg = top; bg = bot; } // upper half block
        if (ch == ' ') fg = runFg == -1 ? bg : runFg; // spaces only need bg; keep fg to extend runs
        if (!open || fg != runFg || bg != runBg)
        {
            if (open) color.Append("[/]");
            color.Append($"[{palette[fg].Hex} on {palette[bg].Hex}]");
            runFg = fg; runBg = bg; open = true;
        }
        color.Append(ch);
    }
    if (open) color.Append("[/]");
    if (r < rows - 1) color.Append('\n');
}

if (Environment.GetEnvironmentVariable("AVATAR_PREVIEW") is { Length: > 0 } prev)
{
    using var img = new Image<Rgb24>(cols, rows * 2);
    for (var y = 0; y < rows * 2; y++)
        for (var x = 0; x < cols; x++) img[x, y] = palette[idx[x, y]].Rgb;
    img.Mutate(c => c.Resize(cols * 12, rows * 24, KnownResamplers.NearestNeighbor));
    img.SaveAsPng(prev);
}

static string Lit(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", "\\n").Replace("\u2580", "\\u2580") + "\"";
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>Generated by tools/AvatarGen. Do not edit by hand (hand-tuning goes in the generator).</auto-generated>");
sb.AppendLine("namespace Abuhakmeh;");
sb.AppendLine();
sb.AppendLine("internal static class Avatar");
sb.AppendLine("{");
sb.AppendLine($"    public const int Columns = {cols};");
sb.AppendLine($"    public const int Rows = {rows};");
sb.AppendLine();
sb.AppendLine("    /// <summary>Monochrome ASCII, one line per row.</summary>");
sb.AppendLine($"    public const string Mono = {Lit(mono.ToString().TrimEnd().Replace("\r", ""))};");
sb.AppendLine();
sb.AppendLine("    /// <summary>Spectre markup using half blocks and a four-color palette.</summary>");
sb.AppendLine($"    public const string Color = {Lit(color.ToString())};");
sb.AppendLine("}");
File.WriteAllText(output, sb.ToString());
Console.WriteLine(mono);
Console.WriteLine($"Wrote {output}");
